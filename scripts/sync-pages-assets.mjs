// Keep the public tour on the exact same design system as the application.
import { readFile, mkdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const templates = await readFile(new URL('internal/app/templates.go', root), 'utf8');
const app = await readFile(new URL('internal/app/app.go', root), 'utf8');
const style = templates.match(/<style>\s*([\s\S]*?)\s*<\/style>/)?.[1];
const theme = app.match(/w\.Write\(\[\]byte\(`(!function\(\)[\s\S]*?\}\(\);)`\)\)/)?.[1];
if (!style || !theme) throw new Error('Could not find the application styles and theme control');
const assets = new Map([
  ['shauth.css', `/* Generated by scripts/sync-pages-assets.mjs from the application. */\n${style}\n`],
  ['theme.js', `// Generated by scripts/sync-pages-assets.mjs from the application.\n${theme}\n`],
  ['favicon.svg', await readFile(new URL('internal/app/assets/favicon.svg', root), 'utf8')],
]);
await mkdir(new URL('docs/demo-assets/', root), { recursive: true });
for (const [name, content] of assets) {
  const target = new URL(`docs/demo-assets/${name}`, root);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) throw new Error(`Run node scripts/sync-pages-assets.mjs: ${name} has drifted`);
  } else {
    await writeFile(target, content);
  }
}
console.log('Pages assets match the application design system');
